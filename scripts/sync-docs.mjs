#!/usr/bin/env node
// Regenerate docs/mcp.md, docs/metrics.md and docs/rest-api.md from the LIVE
// service, so the reference can never drift from what the servers answer:
//   node scripts/sync-docs.mjs                       # https://kotecharts.com
//   KOTE_BASE_URL=http://127.0.0.1:3350 node scripts/sync-docs.mjs
//   node scripts/sync-docs.mjs --check               # exit 1 if docs are stale (CI)
// Zero dependencies (Node 18+).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const base = (process.env.KOTE_BASE_URL ?? 'https://kotecharts.com').replace(/\/$/, '');
const check = process.argv.includes('--check');
const PUBLIC = 'https://kotecharts.com';
// Names itself so the service can tell docs generation apart from real usage.
const USER_AGENT = 'kote-charts-contract-docs/1 (+https://github.com/kote-charts/kote-charts)';

async function getJson(path, init) {
  const res = await fetch(`${base}${path}`, {
    ...init,
    headers: { 'user-agent': USER_AGENT, ...(init?.headers ?? {}) },
    signal: AbortSignal.timeout(60_000),
  });
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  return res.json();
}

let rpcId = 0;
async function rpc(method, params = {}) {
  const body = await getJson('/api/v1/mcp', {
    method: 'POST',
    headers: { 'content-type': 'application/json', accept: 'application/json, text/event-stream' },
    body: JSON.stringify({ jsonrpc: '2.0', id: ++rpcId, method, params }),
  });
  if (body.error) throw new Error(`${method}: ${body.error.message}`);
  return body.result;
}

const md = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const header = (title) =>
  `<!-- Generated by scripts/sync-docs.mjs from ${PUBLIC} — do not edit by hand. -->\n\n# ${title}\n`;

// ---------------------------------------------------------------- MCP
const init = await rpc('initialize', {
  protocolVersion: '2025-06-18',
  capabilities: {},
  clientInfo: { name: 'kote-charts-contract-docs', version: '1' },
});
const { tools } = await rpc('tools/list');
const { resources } = await rpc('resources/list');
const { resourceTemplates } = await rpc('resources/templates/list');
const { prompts } = await rpc('prompts/list');

const mcp = [header('MCP server reference')];
mcp.push(
  `- **Endpoint:** \`POST ${PUBLIC}/api/v1/mcp\` — Streamable HTTP, stateless, JSON responses.`,
  '- **Auth:** none required. Optional API key as `Authorization: Bearer kote_…`.',
  '- **Limits:** without a key, 60 tool calls per minute per IP — `tools/call` and reads of `kote://charts/{id}`; the handshake and discovery requests (`initialize`, `tools/list`, `resources/list`, `prompts/*`, `ping`, the catalog and methodology resources) are not counted against it. With a key, 3 requests per second. Each message of a JSON-RPC batch counts separately. A refused request answers HTTP 429 with `Retry-After`; `X-RateLimit-Limit` / `X-RateLimit-Remaining` are on every response.',
  '- **Headers:** clients must send `Accept: application/json, text/event-stream`.',
  `- **Server:** \`${init.serverInfo.name}\` ${init.serverInfo.version} — ${init.serverInfo.title ?? ''}`,
  '- **Registry:** `com.kotecharts/charts` (official MCP Registry). stdio bridge: `npx -y kotecharts-mcp`.',
  '',
  '## Server instructions',
  '',
  '> ' + md(init.instructions).replaceAll(base, PUBLIC),
  '',
  `## Tools (${tools.length})`,
  '',
);
for (const t of tools) {
  mcp.push(`### \`${t.name}\` — ${t.title ?? ''}`, '', md(t.description).replaceAll(base, PUBLIC), '');
  const props = t.inputSchema?.properties ?? {};
  const required = new Set(t.inputSchema?.required ?? []);
  if (Object.keys(props).length) {
    mcp.push('| Argument | Type | Required | Description |', '|---|---|---|---|');
    for (const [name, p] of Object.entries(props)) {
      const type = p.enum ? p.enum.map((v) => `\`${v}\``).join(' \\| ') : p.type ?? '';
      mcp.push(`| \`${name}\` | ${type} | ${required.has(name) ? 'yes' : ''} | ${md(p.description)} |`);
    }
    mcp.push('');
  }
  if (t.annotations?.readOnlyHint) mcp.push('_Read-only._', '');
}
mcp.push('## Resources', '');
for (const r of resources.filter((x) => !x.uri.startsWith('kote://charts/'))) {
  mcp.push(`- \`${r.uri}\` — ${md(r.title ?? r.name)} (${r.mimeType}): ${md(r.description)}`);
}
for (const r of resourceTemplates) {
  mcp.push(`- \`${r.uriTemplate}\` — ${md(r.title ?? r.name)} (${r.mimeType}): ${md(r.description)}`);
}
mcp.push(`- ${resources.filter((x) => x.uri.startsWith('kote://charts/')).length} chart resources are listed by \`resources/list\`.`, '');
mcp.push('## Prompts', '');
for (const p of prompts) {
  const args = (p.arguments ?? []).map((a) => `\`${a.name}\``).join(', ');
  mcp.push(`- \`${p.name}\`${args ? ` (${args})` : ''} — ${md(p.description)}`);
}
mcp.push('', '## Example', '', '```bash', `curl -s -X POST ${PUBLIC}/api/v1/mcp \\`,
  "  -H 'content-type: application/json' -H 'accept: application/json, text/event-stream' \\",
  `  -d '{"jsonrpc":"2.0","id":1,"method":"tools/call","params":{"name":"get_latest","arguments":{"id":"mvrv-z-score"}}}'`,
  '```', '');

// ------------------------------------------------------------- metrics
const catalog = (await getJson('/api/v1/metrics')).data;
const byCategory = new Map();
for (const m of catalog.metrics) {
  const cat = m.category ?? 'Other';
  if (!byCategory.has(cat)) byCategory.set(cat, []);
  byCategory.get(cat).push(m);
}
const metrics = [header(`Metric catalog (${catalog.total} public charts)`)];
metrics.push(
  `Machine-readable version (live freshness included): \`GET ${PUBLIC}/api/v1/metrics\` — no key.`,
  'Per metric: `GET /api/v1/metrics/{id}`. Data: `GET /api/v1/public/charts/{id}` (API key) or MCP `get_chart`.',
  '',
  '## Input categories',
  '',
  ...Object.entries(catalog.sources).map(([id, s]) => `- \`${id}\` — **${s.name}**: ${md(s.description)}`),
  '',
  '## Units',
  '',
  ...Object.entries(catalog.units).map(([id, label]) => `- \`${id}\` — ${label}`),
  '',
);
for (const [cat, list] of [...byCategory.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  metrics.push(`## ${cat}`, '', '| Chart | Formula | Fields (unit) | Inputs |', '|---|---|---|---|');
  for (const m of list.sort((a, b) => a.id.localeCompare(b.id))) {
    const fields = (m.fields ?? []).map((f) => `\`${f.key}\` (${f.unit})`).join(', ');
    metrics.push(
      `| [${md(m.title)}](${PUBLIC}/c/${m.id}) \`${m.id}\` | ${md(m.formula)} | ${fields} | ${(m.sources ?? []).join(', ')} |`,
    );
  }
  metrics.push('');
}

// ------------------------------------------------------------ REST API
const oa = await getJson('/api/v1/openapi.json');
const rest = [header('REST API reference')];
rest.push(
  md(oa.info.description).replaceAll(base, PUBLIC),
  '',
  `OpenAPI 3 document: [\`${PUBLIC}/api/v1/openapi.json\`](${PUBLIC}/api/v1/openapi.json) · human docs: ${PUBLIC}/docs`,
  '',
  '| Method | Path | operationId | Auth | Summary |',
  '|---|---|---|---|---|',
);
for (const [path, item] of Object.entries(oa.paths).sort()) {
  for (const [method, op] of Object.entries(item)) {
    const auth = op.security?.length ? 'API key' : 'none';
    rest.push(`| ${method.toUpperCase()} | \`${path}\` | \`${op.operationId}\` | ${auth} | ${md(op.summary)} |`);
  }
}
const chartOp = oa.paths['/api/v1/public/charts/{id}']?.get;
if (chartOp?.parameters) {
  rest.push('', '## Query parameters of `getChart`', '', '| Name | Description |', '|---|---|');
  for (const p of chartOp.parameters.filter((x) => x.in === 'query')) rest.push(`| \`${p.name}\` | ${md(p.description)} |`);
}
rest.push(
  '',
  '## Errors',
  '',
  'Every error is `{"success": false, "error": {"code", "message", "requestId"}}` with a matching HTTP status:',
  '400 invalid query · 401 missing/invalid key · 403 blocked or non-public chart · 404 unknown chart · 429 rate limit (`Retry-After`) · 503 temporarily unavailable.',
  '',
);

const outputs = {
  'docs/mcp.md': mcp.join('\n'),
  'docs/metrics.md': metrics.join('\n'),
  'docs/rest-api.md': rest.join('\n'),
};
let stale = 0;
for (const [file, text] of Object.entries(outputs)) {
  const path = join(root, file);
  let prev = '';
  try {
    prev = readFileSync(path, 'utf8');
  } catch {}
  if (check) {
    if (prev !== text) {
      stale += 1;
      console.error(`stale: ${file}`);
    }
  } else {
    writeFileSync(path, text);
    console.log(`wrote ${file} (${(text.length / 1024).toFixed(1)} KB)`);
  }
}
if (check && stale) process.exit(1);
